#!/usr/bin/env node
/**
 * Wrap the Next standalone server entry with a port self-heal supervisor.
 *
 * WHY: the z.ai platform deploy packages `.next/standalone` into
 * next-service-dist and starts it with a plain `bun server.js` — while the
 * container's own boot step ("custom dev script") may hold :3000 with a dev
 * server, or grab it again mid-deploy. The packaged server then dies with
 * EADDRINUSE and the deploy reports "Sorry, there was a problem deploying
 * the code" (2026-11-14 16:42, 19:15).
 *
 * v2 wrapper (self-contained — the packaged dist has no scripts/ dir):
 *   1. frees the port with a PURE /proc scan (works on slim deploy images
 *      that ship neither lsof nor ss — the v1 wrapper died exactly there);
 *      lsof stays as a fast path (SLP_NO_LSOF=1 disables it — test hook
 *      that simulates a no-lsof container);
 *   2. spawns server.real.js as a CHILD, so this process stays alive and
 *      the deploy's liveness check always passes;
 *   3. if the child ever dies (dev grabbed the port back, crash), frees
 *      the port and respawns — the deploy converges instead of dying.
 *
 * v3 adds optional TLS termination (v39 security hardening): when
 * SLP_TLS_CERT + SLP_TLS_KEY env vars point at a PEM cert/key, this wrapper
 * additionally serves HTTPS on PORT (proxying to the child on an internal
 * port) and a tiny HTTP listener that 301-redirects to HTTPS — phones get
 * `https://<server-ip>:3000` with a real certificate and auto-redirect.
 * Without those env vars the behavior is byte-identical to v2 (plain HTTP
 * child on PORT — the platform deploy path).
 *
 * `next build` regenerates server.js on every run, so the mv+wrap step is
 * naturally idempotent per build.
 */
import { existsSync, renameSync, writeFileSync, readFileSync } from 'node:fs';
import { join } from 'node:path';

const dir = '.next/standalone';
const entry = join(dir, 'server.js');
const real = join(dir, 'server.real.js');

if (!existsSync(entry)) {
  console.error('[wrap-standalone] .next/standalone/server.js missing — run next build first');
  process.exit(1);
}

// if a previous wrapper is present, the real server is already preserved
if (!existsSync(real)) {
  renameSync(entry, real);
} else if (readFileSync(entry, 'utf8').includes('slp-port-self-heal')) {
  // wrapper already in place (double run) — regenerate anyway (template may have changed)
}

// no backticks inside — written via String.raw
const wrapper = String.raw`/* slp-port-self-heal v3 — generated by scripts/wrap-standalone.mjs at build time.
   The platform deploy starts this dist with a plain "bun server.js" while the
   container's boot step may hold the same port with a dev server. This
   supervisor: (1) frees the port with a pure /proc scan (works on slim
   containers without lsof/ss), (2) spawns server.real.js as a child so this
   process stays alive for the deploy liveness check, and (3) respawns the
   child if it ever dies (port race, dev restart, crash).
   v3: with SLP_TLS_CERT + SLP_TLS_KEY set it also serves HTTPS on PORT
   (child moves to an internal port) and an HTTP→HTTPS redirect listener. */
const spawn = require('node:child_process').spawn;
const execSync = require('node:child_process').execSync;
const fs = require('node:fs');
const path = require('node:path');

const PORT = String(process.env.PORT || 3000);
const TLS_CERT = process.env.SLP_TLS_CERT || '';
const TLS_KEY = process.env.SLP_TLS_KEY || '';
const TLS_ON = Boolean(TLS_CERT && TLS_KEY);
const CHILD_PORT = TLS_ON ? String(process.env.SLP_CHILD_PORT || 3100) : PORT;
const HTTP_PORT = TLS_ON ? String(process.env.SLP_HTTP_PORT || 3080) : '';
const MAX_RESPAWNS = 20;
let respawns = 0;
let child = null;
let shuttingDown = false;

/* pids of processes LISTENing on the given port — pure /proc, no external binaries */
function procListenerPids(port) {
  const inodes = {};
  const files = ['/proc/net/tcp', '/proc/net/tcp6'];
  for (let fi = 0; fi < files.length; fi++) {
    let raw = '';
    try { raw = fs.readFileSync(files[fi], 'utf8'); } catch (e) { continue; }
    const lines = raw.split('\n');
    for (let i = 1; i < lines.length; i++) {
      const cols = lines[i].trim().split(/\s+/);
      if (cols.length < 10 || cols[3] !== '0A') continue;
      const localPort = parseInt(String(cols[1]).split(':')[1], 16);
      if (localPort === Number(port)) inodes[cols[9]] = true;
    }
  }
  const pids = [];
  let dirs = [];
  try { dirs = fs.readdirSync('/proc'); } catch (e) { return pids; }
  for (let i = 0; i < dirs.length; i++) {
    const d = dirs[i];
    if (!/^[0-9]+$/.test(d)) continue;
    let fds = [];
    try { fds = fs.readdirSync('/proc/' + d + '/fd'); } catch (e) { continue; }
    for (let j = 0; j < fds.length; j++) {
      let link = '';
      try { link = fs.readlinkSync('/proc/' + d + '/fd/' + fds[j]); } catch (e) { continue; }
      const m = link.match(/^socket:\[([0-9]+)\]$/);
      if (m && inodes[m[1]]) { pids.push(Number(d)); break; }
    }
  }
  return pids;
}

/* free the port; lsof is only a fast path (SLP_NO_LSOF=1 simulates a slim
   container without it — the /proc scan must do the job there) */
function freePort(port) {
  const pids = [];
  if (process.env.SLP_NO_LSOF !== '1') {
    try {
      const out = execSync('lsof -t -i tcp:' + port + ' -s tcp:listen 2>/dev/null', {
        shell: '/bin/bash',
        stdio: ['ignore', 'pipe', 'ignore'],
      });
      out.toString().split('\n').forEach(function (l) { const n = Number(l); if (n) pids.push(n); });
    } catch (e) { /* lsof missing or no listener */ }
  }
  if (pids.length === 0) Array.prototype.push.apply(pids, procListenerPids(port));
  let killed = 0;
  for (let i = 0; i < pids.length; i++) {
    const pid = pids[i];
    if (!pid || pid === process.pid) continue;
    try { process.kill(pid, 'SIGKILL'); killed++; } catch (e) { /* gone */ }
  }
  return killed;
}

function boot() {
  const env = Object.assign({}, process.env);
  if (TLS_ON) env.PORT = CHILD_PORT; // the app listens internally; TLS fronts on PORT
  child = spawn(process.execPath, [path.join(__dirname, 'server.real.js')], {
    stdio: 'inherit',
    env: env,
  });
  child.on('exit', function () {
    if (shuttingDown) return;
    respawns++;
    if (respawns > MAX_RESPAWNS) {
      console.error('[slp-self-heal] giving up after ' + MAX_RESPAWNS + ' respawns');
      process.exit(1);
    }
    console.log('[slp-self-heal] server child died — freeing :' + CHILD_PORT + ' and respawning (' + respawns + '/' + MAX_RESPAWNS + ')');
    setTimeout(function () { freePort(CHILD_PORT); boot(); }, 400);
  });
}

/* v3 TLS front-end: HTTPS on PORT proxying to the child + HTTP redirect.
   The front servers live in THIS supervisor process, so they survive child
   respawns untouched. */
function startTls() {
  const http = require('node:http');
  const https = require('node:https');
  const tlsOpts = {
    cert: fs.readFileSync(TLS_CERT),
    key: fs.readFileSync(TLS_KEY),
  };
  const proxy = function (req, res) {
    // serve the CA certificate itself for one-tap phone installs — always
    // in sync with the cert actually in use, independent of build snapshots
    if (req.url === '/ca.crt' || req.url.indexOf('/ca.crt?') === 0) {
      try {
        const pem = fs.readFileSync(TLS_CERT);
        res.writeHead(200, {
          'content-type': 'application/x-x509-ca-cert',
          'content-disposition': 'attachment; filename="slp-billing-ca.crt"',
        });
        res.end(pem);
      } catch (e) {
        res.writeHead(500);
        res.end('certificate missing');
      }
      return;
    }
    const headers = Object.assign({}, req.headers, {
      'x-forwarded-proto': 'https',
      'x-forwarded-ssl': 'on',
    });
    const up = http.request({
      hostname: '127.0.0.1',
      port: Number(CHILD_PORT),
      path: req.url,
      method: req.method,
      headers: headers,
    }, function (ur) {
      // forward everything except hop-by-hop headers
      const h = {};
      for (const k in ur.headers) {
        if (k === 'connection' || k === 'keep-alive' || k === 'transfer-encoding') continue;
        h[k] = ur.headers[k];
      }
      res.writeHead(ur.statusCode || 502, h);
      ur.pipe(res);
    });
    up.on('error', function () {
      try {
        res.writeHead(502, { 'content-type': 'text/plain; charset=utf-8' });
        res.end('SLP Billing server is starting…');
      } catch (e) { /* client already gone */ }
    });
    req.pipe(up);
  };
  https.createServer(tlsOpts, proxy).listen(Number(PORT), function () {
    console.log('[slp-tls] HTTPS ready on :' + PORT + ' → app on 127.0.0.1:' + CHILD_PORT + ' (cert: ' + TLS_CERT + ')');
  });
  http.createServer(function (req, res) {
    const host = String(req.headers.host || '').split(':')[0] || 'localhost';
    res.writeHead(301, { Location: 'https://' + host + ':' + PORT + req.url });
    res.end();
  }).listen(Number(HTTP_PORT), function () {
    console.log('[slp-tls] HTTP :' + HTTP_PORT + ' redirects to HTTPS :' + PORT);
  });
}

function forward(sig) {
  process.on(sig, function () {
    shuttingDown = true;
    if (child) { try { child.kill(sig); } catch (e) { /* already gone */ } }
    process.exit(0);
  });
}
forward('SIGTERM');
forward('SIGINT');

freePort(PORT);
if (TLS_ON) freePort(CHILD_PORT);
if (TLS_ON) freePort(HTTP_PORT);
boot();
if (TLS_ON) startTls();
`;

writeFileSync(entry, wrapper);
console.log('[wrap-standalone] server.js wrapped — /proc self-heal + supervisor respawn active (PORT or 3000)');
