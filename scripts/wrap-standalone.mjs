#!/usr/bin/env node
/**
 * Wrap the Next standalone server entry with a port self-heal pre-flight.
 *
 * WHY: the z.ai platform deploy packages `.next/standalone` into
 * next-service-dist and starts it with a plain `bun server.js` — while the
 * container's own boot step ("custom dev script") runs `bun run dev` which
 * HOLDS :3000. The packaged server then dies with EADDRINUSE and the deploy
 * reports "Sorry, there was a problem deploying the code". This happened on
 * every deploy that ran while a dev server was up (2026-11-14 19:14/19:15).
 *
 * The wrapper is self-contained (the packaged dist has no scripts/ dir):
 * it frees the configured port (lsof primary, ss fallback) and boots the
 * real server (renamed server.real.js) ~500 ms later, inside the SAME
 * process — so the deploy start script's liveness check still passes.
 *
 * `next build` regenerates server.js on every run, so the mv+wrap step is
 * naturally idempotent per build.
 */
import { existsSync, renameSync, writeFileSync, readFileSync } from 'node:fs';
import { join } from 'node:path';

const dir = '.next/standalone';
const entry = join(dir, 'server.js');
const real = join(dir, 'server.real.js');

if (!existsSync(entry)) {
  console.error('[wrap-standalone] .next/standalone/server.js missing — run next build first');
  process.exit(1);
}

// if a previous wrapper is present, the real server is already preserved
if (!existsSync(real)) {
  renameSync(entry, real);
} else if (readFileSync(entry, 'utf8').includes('slp-port-self-heal')) {
  // wrapper already in place (double run) — nothing to do
  console.log('[wrap-standalone] already wrapped');
  process.exit(0);
} else {
  // unexpected state: server.js rewritten but real missing — treat entry as real
  renameSync(entry, real);
}

// no backticks inside — written via String.raw template
const wrapper = String.raw`/* slp-port-self-heal — generated by scripts/wrap-standalone.mjs at build time.
   Frees the serving port before booting the real standalone server, so the
   platform deploy ('bun server.js') survives a dev server still holding it. */
const { execSync } = require('node:child_process');
const port = String(process.env.PORT || 3000);
const kills = [
  'lsof -t -i tcp:' + port + ' -s tcp:listen | xargs -r kill -9',
  'ss -tlnp | grep ":' + port + ' " | grep -oP "pid=\\K\\d+" | sort -u | xargs -r kill -9',
];
for (const cmd of kills) {
  try { execSync(cmd, { stdio: 'ignore', shell: '/bin/bash' }); } catch (e) { /* no listener */ }
}
setTimeout(function () { require('./server.real.js'); }, 500);
`;

writeFileSync(entry, wrapper);
console.log('[wrap-standalone] server.js wrapped — port self-heal active (PORT or 3000)');
