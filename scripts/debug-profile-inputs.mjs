import { chromium } from 'playwright';
const BASE = process.env.BASE_URL || 'http://localhost:3100';
const browser = await chromium.launch({ args: ['--disable-dev-shm-usage'] });
const ctx = await browser.newContext({ viewport: { width: 390, height: 844 }, isMobile: true, hasTouch: true });
const page = await ctx.newPage();
page.on('pageerror', (e) => console.log('PAGEERR', String(e).slice(0, 160)));
await page.addInitScript(() => localStorage.setItem('slp-update-notice-seen', '37'));
await page.goto(BASE, { waitUntil: 'domcontentloaded' });
await page.waitForTimeout(3000);
await page.locator('[data-staff-login-link]').click();
await page.getByLabel('Staff ID').fill('MDN');
await page.getByLabel('Staff password or MPIN').fill('mdn');
await page.getByRole('button', { name: 'Staff sign in' }).click();
await page.locator('[data-header]').waitFor({ state: 'visible', timeout: 20000 });
await page.waitForTimeout(800);
console.log('first-login dialog:', await page.getByRole('button', { name: 'Continue with current password' }).count());
await page.getByRole('button', { name: 'Continue with current password' }).click();
await page.waitForTimeout(800);
await page.locator('[aria-label="Main navigation"] button', { hasText: 'Profile' }).first().click();
await page.waitForTimeout(1200);
console.log('inputs:', JSON.stringify(await page.locator('input').evaluateAll((els) => els.map((e) => ({ label: e.getAttribute('aria-label'), id: e.id, type: e.type })))));
console.log('staff null?', await page.evaluate(() => localStorage.getItem('slp-auth-v1')?.slice(0, 30)));
console.log('profile text:', JSON.stringify(((await page.textContent('main')) || '').replace(/\s+/g, ' ').slice(0, 200)));
await browser.close();
